uint16_t crc16_update(uint8_t const *p_data, size_t data_len, uint16_t const *p_crc)
{
   uint16_t crc_calc = 0xFFFF;

   if(p_crc != NULL)
   {
      crc_calc = *p_crc;
   }

   for(size_t idx = 0; idx < data_len; idx++)
   {
// This calculation uses truncation intentionally
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wconversion"
      crc_calc = (uint8_t)(crc_calc >> 8) | (crc_calc << 8); // NOSONAR - intentional trunction to uint8_t
      crc_calc ^= p_data[idx];
      crc_calc ^= (uint8_t)(crc_calc & 0xFF) >> 4;
      crc_calc ^= (crc_calc << 8) << 4;
      crc_calc ^= ((crc_calc & 0xFF) << 4) << 1;
#pragma GCC diagnostic pop
   }

   return crc_calc;
}
